    w("            }")
    w("            if (more)")
    store("1 - cur", "            ")
    w("            Group.Barrier();")
    w("            cur = 1 - cur;")
    w("        }")
    for mt in range(MT5):
        for nt in range(NT5):
            w("        {")
            w(f"            int m0 = tileRow * BM + wm * 64 + {mt * 16} + g, m1 = m0 + 8;")
            w(f"            int n0 = tileCol * BN + wn * 64 + {nt * 8} + 2 * t, n1 = n0 + 1;")
            if acc:
                w(f"            if (m0 < M) {{ if (n0 < N) {{ long i = (long)m0 * N + n0; C[i] = c{mt}{nt}0 * inv + D[i]; }} if (n1 < N) {{ long i = (long)m0 * N + n1; C[i] = c{mt}{nt}1 * inv + D[i]; }} }}")
