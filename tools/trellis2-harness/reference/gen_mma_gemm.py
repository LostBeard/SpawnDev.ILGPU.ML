    w(f"        int aLd = (wm * 64 + (lane & 15)) * {RW} + (lane >> 4) * 4;")
    w(f"        int bLd = (wn * 32 + (lane & 7) + ((lane >> 4) << 3)) * {RW} + ((lane >> 3) & 1) * 4;")

