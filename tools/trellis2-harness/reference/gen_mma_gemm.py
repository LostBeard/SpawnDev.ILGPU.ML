                w("            {")
                w("                int seg = n0 < N0 ? 0 : (n0 < N0 + N1 ? 1 : 2);")
                w("                int ns = seg == 0 ? N0 : (seg == 1 ? N1 : N - N0 - N1), nc = seg == 0 ? n0 : (seg == 1 ? n0 - N0 : n0 - N0 - N1);")
