# KernelExact (2026-11-18; fp16 halves since 2026-11-19): the same flash attention at fp32 accuracy. q, k, v and the probabilities are each kept as
# two fp16 values, hi = fp16(x) and lo = fp16(x - hi) (x - hi is exact in fp32), so a product a * b is hi_a hi_b + lo_a hi_b + hi_a lo_b: three MMAs
# where the fast kernel runs one (the dropped lo_a lo_b is 2^-22 of the product, the size of lo's own rounding). fp16's 11 bits a half give 22 bits
# a value where bf16's 8 gave 16; fp16's narrow range is met by power-of-two scales (exact): q, the centred k and v each scaled so their largest
# |value| lands in [2^14, 2^15) (MaxAbs writes the three maxima, Pow2Scale turns one into its scale), the probabilities (at most 1) by 2^14, and
# the scales folded back into the softmax scale and the final normalisation. MEASURED 2026-11-19 (float64 emulation on LTX-2's own guided
# self-attention, blocks 0 / 24 / 47): bf16 halves 3.0e-6 to 3.4e-6 from float64 (the kernel: 3.0e-6 to 3.3e-6, the emulation is its arithmetic),
# fp16 halves 5.7e-8 to 5.9e-8, the fp32 portable kernel 1.7e-7 to 2.0e-7. The bf16 form's 3e-6 failed the two-guide ComfyUI gate (1.2e-4).
# Every k16 step runs its three MMAs from zero and adds the result to the fp32 accumulators with an ordinary add: the tensor cores' own
# accumulation truncates (see gen_mma_gemm.py kernel_split).
# K / V arrive as interleaved words (hi pair at [2p], lo pair at [2p + 1]). Both halves of a tile must fit the 48 KB of static shared memory, so
# a tile is 32 keys: Ks 32 x 68 words and Vt 128 x 20 words, twice.
# ---------------------------------------------------------------------------------------------------------------------------------------------
