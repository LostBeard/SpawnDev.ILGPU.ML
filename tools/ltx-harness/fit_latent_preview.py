"""Fit the live-preview colours of a video model: a linear map (one 3 x C matrix and a bias) from a model-space latent voxel to the average colour of the pixels it decodes to,
by least squares over clips decoded by OUR pipeline (Examples/11.VideoGen.Console --save-latent: latent.f32 + latent.json + frame_*.png). The preview then shows a sampler's
current x0 estimate as a tiny video at every step without running the VAE.

  python fit_latent_preview.py MODEL OUT.cs CLIP_DIR [CLIP_DIR ...]          MODEL = ltx | wan
The latent voxel (f, i, j) covers pixel frame 0 for f = 0 and frames R*(f-1)+1 .. R*f after (the causal VAEs: R = 8 for LTX, 4 for Wan), and an S x S pixel block (S = 32 / 16).
Pixels are mapped to [-1, 1]. Prints the fit's R^2 per channel and writes the C# table (namespace SpawnDev.ILGPU.ML, partial class LatentPreview).
"""
import json
import os
import sys

import numpy as np
from PIL import Image

CFG = {"ltx": (128, 8, 32), "wan": (48, 4, 16)}


def samples(model, d):
    C, R, S = CFG[model]
    meta = json.load(open(os.path.join(d, "latent.json")))
    assert meta["model"] == model, (d, meta["model"])
    F, H, W = meta["frames"], meta["height"], meta["width"]
    Fz, h, w = (F - 1) // R + 1, H // S, W // S
    z = np.fromfile(os.path.join(d, "latent.f32"), dtype="<f4").reshape(C, Fz, h, w)
    frames = np.stack([np.asarray(Image.open(os.path.join(d, f"frame_{k:04d}.png")).convert("RGB"), dtype=np.float32) for k in range(F)]) / 127.5 - 1.0
    X, Y = [], []
    for f in range(Fz):
        ks = [0] if f == 0 else list(range(R * (f - 1) + 1, R * f + 1))
        block = frames[ks].mean(axis=0)                                       # [H, W, 3]
        pooled = block.reshape(h, S, w, S, 3).mean(axis=(1, 3))               # [h, w, 3]
        X.append(z[:, f].reshape(C, -1).T)
        Y.append(pooled.reshape(-1, 3))
    return np.concatenate(X), np.concatenate(Y)


def main():
    model, out, dirs = sys.argv[1], sys.argv[2], sys.argv[3:]
    C = CFG[model][0]
    parts = [samples(model, d) for d in dirs]
    X = np.concatenate([p[0] for p in parts]).astype(np.float64)
    Y = np.concatenate([p[1] for p in parts]).astype(np.float64)
    A = np.concatenate([X, np.ones((len(X), 1))], axis=1)
    lam = 1e-3 * len(X)                                                       # a little ridge: the latent channels are correlated
    reg = lam * np.eye(C + 1); reg[C, C] = 0
    coef = np.linalg.solve(A.T @ A + reg, A.T @ Y)                           # [C + 1, 3]
    pred = A @ coef
    r2 = 1 - ((pred - Y) ** 2).sum(0) / ((Y - Y.mean(0)) ** 2).sum(0)
    print(f"{model}: {len(X)} voxels from {len(dirs)} clips; R^2 per channel (R, G, B): {np.round(r2, 3).tolist()}")
    name = "Ltx" if model == "ltx" else "Wan"
    rows = ",\n            ".join(", ".join(f"{v:.5f}f" for v in coef[c]) for c in range(C))
    bias = ", ".join(f"{v:.5f}f" for v in coef[C])
    src = f"""// <auto-generated> tools/ltx-harness/fit_latent_preview.py {model}: a least-squares fit over {len(dirs)} clips decoded by this library ({len(X)} latent voxels,
// R^2 per colour channel {np.round(r2, 3).tolist()}). Do not edit by hand. </auto-generated>
namespace SpawnDev.ILGPU.ML;

public sealed partial class LatentPreview
{{
    /// <summary>The live-preview colours of the {"LTX-Video 0.9.8" if model == "ltx" else "Wan 2.2 TI2V-5B"} latent ({C} channels): [{C}, 3] row-major, then the bias.</summary>
    private static readonly float[] {name}Factors =
        {{
            {rows}
        }};
    private static readonly float[] {name}Bias = {{ {bias} }};
}}
"""
    open(out, "w", encoding="utf-8").write(src)
    print("wrote", out)


if __name__ == "__main__":
    main()
